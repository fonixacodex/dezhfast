import subprocess

import typer
from rich.console import Console

app = typer.Typer(help="Database migrations (Alembic wrapper).")
console = Console()


def _run(cmd: list[str]) -> None:
    try:
        subprocess.run(cmd, check=True)
    except FileNotFoundError:
        console.print("[bold red]✗ alembic not installed. Run `pip install alembic`.[/bold red]")
        raise typer.Exit(1) from None
    except subprocess.CalledProcessError:
        console.print("[bold red]✗ command failed.[/bold red]")
        raise typer.Exit(1) from None   # ← این خط تغییر کرد


@app.command()
def init() -> None:
    """Initialize Alembic (alembic init migrations)."""
    _run(["alembic", "init", "migrations"])
    console.print("[bold green]✓ Alembic initialized.[/bold green]")


@app.command("make")
def make(message: str = typer.Argument(..., help="Migration message")) -> None:
    """Create a new autogenerated migration."""
    console.print(f"[yellow]→ creating migration:[/yellow] {message}")
    _run(["alembic", "revision", "--autogenerate", "-m", message])
    console.print("[bold green]✓ migration created.[/bold green]")


@app.command()
def up() -> None:
    """Apply all pending migrations (upgrade head)."""
    console.print("[yellow]→ applying migrations...[/yellow]")
    _run(["alembic", "upgrade", "head"])
    console.print("[bold green]✓ migrations applied.[/bold green]")


@app.command()
def down(steps: int = typer.Option(1, "--steps", "-n")) -> None:
    """Rollback N migrations."""
    console.print(f"[yellow]→ rolling back {steps} step(s)...[/yellow]")
    _run(["alembic", "downgrade", f"-{steps}"])
    console.print("[bold green]✓ rollback done.[/bold green]")


@app.command()
def status() -> None:
    """Show current migration status."""
    _run(["alembic", "current"])